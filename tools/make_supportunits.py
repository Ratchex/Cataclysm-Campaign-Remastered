"""Cataclysm's Support Units for the runtime (cataclysmkas.lua KAS_SU*): each ship's cost and what it provides, from
the .shp files (supportUnits / providesSU, cataclysm.exe's ShipStaticInfo +0x410 / +0x414), by HWRM ship type
(tools/shipmap.tsv), plus the Kuun-Lan modules (subsystems here: by hardpoint name, smt_ms_sp.ship).

  data/scripts/cataclysm/supportunits_gen.lua
    CatSU_Cost[type]         SU a ship of the type uses
    CatSU_Provides[type]     SU it adds to the player's limit
    CatSU_Hardpoints[name]   SU a Kuun-Lan module on that hardpoint adds

Usage: make_supportunits.py
"""
import csv
import glob
import os
import re

DECOMP = r"C:\Modding\Cataclysm-decomp"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIG = os.path.join(DECOMP, "extracted", "big")
# HWRM types with no shipmap row: the Mimics' linked MCVs (Cataclysm's sMCV, shiprules.lua), the other Kuun-Lan
EXTRA = {"smt_mcv_ioncannonfrigate": "smcv", "smt_mcv_supportfrigate": "smcv", "smt_ms": "smothership"}
# Kuun-Lan modules (tools/make_modules.py: subsystems on these hardpoints of smt_ms_sp)
HARDPOINTS = {"Hangar Module": "smothershipdockingbay"}
HARDPOINTS.update({f"Support Module {n}": "smothershipsupport" for n in range(1, 13)})


def shp_values():
    out = {}
    for path in glob.glob(os.path.join(BIG, "race_*", "*.shp")):
        text = open(path, encoding="latin-1").read()
        su = re.search(r"^supportUnits\s+(-?\d+)", text, re.M | re.I)
        pv = re.search(r"^providesSU\s+(-?\d+)", text, re.M | re.I)
        out[os.path.splitext(os.path.basename(path))[0].lower()] = (int(su.group(1)) if su else 0,
                                                                     int(pv.group(1)) if pv else 0)
    return out


def main():
    vals = shp_values()
    rows = list(csv.DictReader(open(os.path.join(MOD, "tools", "shipmap.tsv"), encoding="utf-8"), delimiter="\t"))
    types = {}
    for r in rows:
        if r["hwrm"] and r["ship"].lower() in vals:
            types.setdefault(r["hwrm"].lower(), r["ship"].lower())
    types.update(EXTRA)
    out = os.path.join(MOD, "data", "scripts", "cataclysm", "supportunits_gen.lua")
    with open(out, "w", encoding="latin-1", newline="\n") as f:
        f.write("-- Generated by tools/make_supportunits.py: Cataclysm's Support Units (.shp supportUnits / providesSU)\n")
        f.write("CatSU_Cost = {\n")
        for t in sorted(types):
            if vals[types[t]][0] > 0:
                f.write(f'    ["{t}"] = {vals[types[t]][0]},   -- {types[t]}\n')
        f.write("}\nCatSU_Provides = {\n")
        for t in sorted(types):
            if vals[types[t]][1] > 0 and not t.endswith("_dummy"):
                f.write(f'    ["{t}"] = {vals[types[t]][1]},   -- {types[t]}\n')
        f.write("}\nCatSU_Hardpoints = {\n")
        for hp, cat in HARDPOINTS.items():
            f.write(f'    ["{hp}"] = {vals[cat][1]},   -- {cat}\n')
        f.write("}\n")
    print(out)


if __name__ == "__main__":
    main()
