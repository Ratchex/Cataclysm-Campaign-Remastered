"""Write data/scripts/scar/cataclysmships.lua from tools/shipmap.tsv: Cataclysm ship type -> HWRM ship type, for
runtime calls that take a type name (kasfShipsSelectType, kasfEnableShipConstruction, ship spawning).
Types without an HWRM ship map to KAS_PlaceholderType, like mission2level.py's --placeholder.

Usage: make_shipmap_lua.py
"""
import csv
import os

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    rows = list(csv.DictReader(open(os.path.join(MOD, "tools", "shipmap.tsv"), encoding="utf-8"), delimiter="\t"))
    out = os.path.join(MOD, "data", "scripts", "scar", "cataclysmships.lua")
    with open(out, "w", encoding="latin-1", newline="\n") as f:
        f.write("-- Generated by tools/make_shipmap_lua.py from tools/shipmap.tsv. Keys are lower case.\n")
        f.write('KAS_PlaceholderType = "Kus_Scout"\nKAS_ShipTypes = {}\n')
        n = 0
        for r in rows:
            if r["hwrm"]:
                f.write(f'KAS_ShipTypes["{r["ship"].lower()}"] = "{r["hwrm"]}"\n')
                n += 1
    print(f"{out}: {n} of {len(rows)} ship types mapped")


if __name__ == "__main__":
    main()
