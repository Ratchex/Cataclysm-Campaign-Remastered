"""Generate data/scripts/scar/cataclysmkas_stubs.lua: a logging stub for every K_<addr> KAS API function called
by any translated mission (*_kas.lua), named from the call-site comments. cataclysmkas.lua loads after this and
replaces the stubs it implements.

Usage: make_kas_stubs.py <mod_root>
"""
import glob
import os
import re
import sys


def main():
    root = sys.argv[1]
    names = {}
    for p in glob.glob(os.path.join(root, "data", "leveldata", "campaign", "cataclysm", "*", "*_kas.lua")):
        for addr, name in re.findall(r"\bK_([0-9a-f]{6})\([^\n]*?(?:--\[\[(\w+)\]\])?$", open(p, encoding="latin-1").read(), re.M):
            if name or addr not in names:
                names[addr] = name
    core = open(os.path.join(root, "data", "scripts", "scar", "cataclysmkas.lua"), encoding="latin-1").read()
    implemented = set(re.findall(r"^function K_([0-9a-f]{6})\(", core, re.M))
    lines = ["-- Generated by tools/make_kas_stubs.py. Do not edit: implement functions in cataclysmkas.lua instead.",
             f"-- {len(names)} KAS API functions used by translated missions; {len(implemented & set(names))} "
             "implemented in cataclysmkas.lua.", ""]
    for addr in sorted(names):
        n = names[addr] or "unnamed"
        lines.append(f'function K_{addr}(...) return KAS_Stub("{addr}", "{n}") end')
    out = os.path.join(root, "data", "scripts", "scar", "cataclysmkas_stubs.lua")
    with open(out, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {len(names)} stubs, {len(implemented & set(names))} of them implemented in cataclysmkas.lua")


if __name__ == "__main__":
    main()
