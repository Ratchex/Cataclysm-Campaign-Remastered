"""Generate data/scripts/scar/cataclysmkas_stubs.lua: a logging stub for every K_<addr> KAS API function called
by any translated mission (*_kas.lua) that cataclysmkas.lua does not implement yet. Names come from the decomp's
kas_api.tsv. Implemented functions must not get a stub: HWRM's Lua refuses to redefine a function.

Usage: make_kas_stubs.py <mod_root>
"""
import glob
import os
import re
import sys

KAS_API = r"C:\Modding\Cataclysm-decomp\out\kas_api.tsv"


def main():
    root = sys.argv[1]
    api = {}
    for line in open(KAS_API, encoding="utf-8").read().splitlines()[1:]:
        c = line.split("\t")
        api[c[0][2:]] = c[1]
    names = {}
    for p in glob.glob(os.path.join(root, "data", "leveldata", "campaign", "cataclysm", "*", "*_kas.lua")):
        for addr in re.findall(r"\bK_([0-9a-f]{6})\(", open(p, encoding="latin-1").read()):
            names[addr] = api.get(addr, "")
    core = open(os.path.join(root, "data", "scripts", "scar", "cataclysmkas.lua"), encoding="latin-1").read()
    implemented = set(re.findall(r"^function K_([0-9a-f]{6})\(", core, re.M))
    done = implemented & set(names)
    lines = ["-- Generated by tools/make_kas_stubs.py. Do not edit: implement functions in cataclysmkas.lua and rerun,",
             "-- which drops their stubs (HWRM cannot redefine a function).",
             f"-- {len(names)} KAS API functions used by translated missions; {len(done)} implemented.", ""]
    for addr in sorted(names):
        if addr in implemented:
            continue
        lines.append(f'function K_{addr}(...) return KAS_Stub("{addr}", "{names[addr] or "unnamed"}") end')
    out = os.path.join(root, "data", "scripts", "scar", "cataclysmkas_stubs.lua")
    with open(out, "w", encoding="latin-1", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {len(names) - len(done)} stubs; {len(done)} of {len(names)} used functions implemented")


if __name__ == "__main__":
    main()
