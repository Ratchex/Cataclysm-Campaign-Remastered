"""Cataclysm's team colours (teamcolors.script: 8 colour schemes, each a faction) for the HWRM missions.

HW1 (Teams.c teReset, LevelLoad.c): a ship's colours are colour scheme N's; N is the ship's owning player unless the
mission's Ships line gives colorScheme(N) (Mission01: Taiidan 2, the Kiith 4 / 6 / 7), and kasfShipsSetColor
changes it. HWRM colours by player (the mission's teamcolour.lua), plus SobGroup_SetTeamColours per group: Gearbox's
KASUtil KAS_SetColourScheme does that from KAS_ColourSchemes, filled at mission start (cataclysmkas.lua
KAS_ApplyColourSchemes) from

  data/scripts/scar/cataclysmcolours.lua   CatColourSchemes[N] = { base, stripe, badge, trail colour, trail texture }

and the teams' schemes from tools/mission2level.py (KAS_TeamSchemes in m<NN>_paths.lua). teamcolour(...) writes a
mission's teamcolour.lua: each player in the scheme most of its teams use (the player: scheme 0).

Badges: stock HWRM's (FACTIONS; Cataclysm has none). Trails: control point 1 of the
scheme's TrailColor (the bright one).

Usage: make_colours.py   (build_mission.py runs it)
"""
import os
import re
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
SCRIPT = r"C:\Modding\Cataclysm-decomp\extracted\big\teamcolors.script"

# scheme -> (faction in teamcolors.script's comments, badge, HWRM trail texture)
FACTIONS = {
    0: ("Kiith Somtaaw", "DATA:Badges/Kushan.tga", "data:/effect/trails/kus_trail_clr.tga"),
    1: ("Beast", "DATA:Badges/hm3_black.tga", "data:/effect/trails/kus_trail_clr.tga"),
    2: ("Taiidan Imperialists", "DATA:Badges/Taiidan.tga", "data:/effect/trails/tai_trail_clr.tga"),
    3: ("Taiidan Loyalists", "DATA:Badges/taiidan2.tga", "data:/effect/trails/tai_trail_clr.tga"),
    4: ("Kiith Manaan", "DATA:Badges/kiith manaan.tga", "data:/effect/trails/kus_trail_clr.tga"),
    5: ("Pirates", "DATA:Badges/Taiidan.tga", "data:/effect/trails/tai_trail_clr.tga"),
    6: ("Kiith Naabal", "DATA:Badges/kiith naabal.tga", "data:/effect/trails/kus_trail_clr.tga"),
    7: ("Kiith S'jet", "DATA:Badges/kiith sjet.tga", "data:/effect/trails/kus_trail_clr.tga"),
}
# all stock HWRM badges (Cataclysm has none; no stock Somtaaw / Beast badge: Kushan's and a plain one for now)
BADGES = []


def read():
    """scheme -> {base, stripe, trail} as 0..1 RGB."""
    s = {}
    for line in open(SCRIPT, encoding="latin-1"):
        line = line.split(";")[0].split("//")[0]
        m = re.match(r"\s*(BaseColor|StripeColor)\s+(\d+),\s*(\d+),\s*(\d+),\s*(\d+)", line)
        if m:
            s.setdefault(int(m.group(2)), {})[m.group(1)] = tuple(int(v) / 255 for v in m.group(3, 4, 5))
        m = re.match(r"\s*TrailColor\s+(\d+),\s*1,\s*(\d+),\s*(\d+),\s*(\d+)", line)
        if m:
            s.setdefault(int(m.group(1)), {})["trail"] = tuple(int(v) / 255 for v in m.group(2, 3, 4))
    return s


def lua_rgb(c):
    return "{" + ", ".join(f"{v:.3f}" for v in c) + "}"


def entry(schemes, n):
    s = schemes[n]
    _, badge, trail = FACTIONS[n]
    return f'{lua_rgb(s["BaseColor"])}, {lua_rgb(s["StripeColor"])}, "{badge}", {lua_rgb(s["trail"])}, "{trail}"'


def teamcolour(path, players, team_schemes, team_players):
    """players: {index: race}; team_schemes: {team: scheme}; team_players: {team: owning player}."""
    schemes = read()
    lines = ["-- Generated by tools/make_colours.py: each player in the colour scheme most of its teams use",
             "-- (Cataclysm teamcolors.script; the groups' own schemes are set at mission start)", "teamcolours = {"]
    for p in sorted(players):
        votes = Counter(team_schemes[t] for t in team_schemes if team_players.get(t) == p)
        n = 0 if p == 0 else (votes.most_common(1)[0][0] if votes else 2)
        lines.append(f"\t[{p}] = {{{entry(schemes, n)}}},   -- {players[p]}: scheme {n}, {FACTIONS[n][0]}")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines + ["}", ""]))


def main():
    schemes = read()
    out = ["-- Generated by tools/make_colours.py from Cataclysm's teamcolors.script: colour scheme N =",
           "-- { base, stripe, badge, trail colour, trail texture } (KAS_SetColourSchemeColours' arguments)",
           "CatColourSchemes = {}"]
    for n in sorted(schemes):
        out.append(f"CatColourSchemes[{n}] = {{{entry(schemes, n)}}}   -- {FACTIONS[n][0]}")
    path = os.path.join(MOD, "data", "scripts", "scar", "cataclysmcolours.lua")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{path}: {len(schemes)} colour schemes")


if __name__ == "__main__":
    main()
