"""Build one translated Cataclysm mission into data/leveldata/campaign/cataclysm/m<NN>/:
  m<NN>.level       mission2level.py output (placeholder ships for races not built yet)
  m<NN>_kas.lua     kas2lua.py translation of the mission's code
  m<NN>.lua         wrapper: loads the KAS libraries + runtime + translation, wires OnInit like Gearbox's port
  datfiles.lua, teamcolour.lua, and ui/mapthumbnails/campaign/cataclysm/m<NN>.dds (from the loading screen)
Then regenerates the runtime stubs.

Usage: build_mission.py <NN> [--fleet "smt_ms_sp,smt_scout*3,smt_worker*2"] [--background ez01] [--intro n01]
"""
import argparse
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
DECOMP = r"C:\Modding\Cataclysm-decomp"

WRAPPER = '''-- m{nn}.lua: Cataclysm Mission{nn}, translated from cataclysm.exe (see m{nn}_kas.lua). Generated by build_mission.py.
dofilepath("data:scripts/SCAR/SCAR_Util.lua")
dofilepath("data:scripts/SCAR/KASUtil.lua")
dofilepath("data:scripts/SCAR/SinglePlayerFlow.lua")
dofilepath("data:scripts/SCAR/SinglePlayerNIS.lua")
dofilepath("data:scripts/SCAR/SinglePlayerHyperspace.lua")
dofilepath("data:scripts/SCAR/SpecialFlags.lua")
dofilepath("data:scripts/scar/cataclysmkas_stubs.lua")
dofilepath("data:scripts/scar/cataclysmkas.lua")
dofilepath("data:scripts/scar/cataclysmspeech.lua")
dofilepath("data:scripts/scar/cataclysmships.lua")
dofilepath("data:scripts/scar/cataclysmtech.lua")
dofilepath("data:leveldata/campaign/cataclysm/m{nn}/m{nn}_kas.lua")

function OnStartOrLoad()
    print("CATACLYSM Mission{nn}: OnStartOrLoad")
    Sound_SpeechSubtitlePath(KAS_SpeechPath)
end

function OnInit()
    print("CATACLYSM Mission{nn}: OnInit")
    KAS_StartEngine()
    KAS_RunAfterIntro("{intro}", Mission{nn}_Start)
end

function Mission{nn}_Start()
    KASRule_Add("Mission{nn}", "Watch_Mission{nn}", "OnInit")
    KAS_Team = "Mission{nn}"
    Init_Mission{nn}("Mission{nn}")
end
'''

DATFILES = '''Dictionaries =
{
\t{
\t\tname = "locale:leveldata/campaign/cataclysm/speech.dat",
\t},
}
'''


def run(*args):
    r = subprocess.run([sys.executable, *args], capture_output=True, text=True)
    print(r.stdout.strip())
    if r.returncode:
        print(r.stderr)
        sys.exit(r.returncode)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("nn")
    ap.add_argument("--fleet", default="smt_ms_sp,smt_scout*3,smt_worker*2")
    ap.add_argument("--background", default="ez01")
    ap.add_argument("--intro", default="", help="cutscene played before the mission starts (e.g. n01)")
    a = ap.parse_args()
    nn = a.nn.zfill(2)
    src = os.path.join(DECOMP, "extracted", "big", "singleplayer", f"mission{nn}")
    out = os.path.join(MOD, "data", "leveldata", "campaign", "cataclysm", f"m{nn}")
    os.makedirs(out, exist_ok=True)
    lvl = ["--shipmap", os.path.join(HERE, "shipmap.tsv"), "--placeholder", "Kus_Scout", "--background", a.background,
           "--player-race", "Somtaaw"]
    if a.fleet:
        lvl += ["--player-fleet", a.fleet]
    run(os.path.join(HERE, "mission2level.py"), src, os.path.join(out, f"m{nn}.level"), *lvl)
    run(os.path.join(HERE, "kas2lua.py"), DECOMP, f"Mission{nn}", src, os.path.join(out, f"m{nn}_kas.lua"))
    with open(os.path.join(out, f"m{nn}.lua"), "w", newline="\n") as f:
        f.write(WRAPPER.format(nn=nn, intro=a.intro))
    test = os.path.join(MOD, "data", "leveldata", "campaign", "cataclysm", "m00_test")
    shutil.copyfile(os.path.join(test, "teamcolour.lua"), os.path.join(out, "teamcolour.lua"))
    with open(os.path.join(out, "datfiles.lua"), "w", newline="\n") as f:
        f.write(DATFILES)
    run(os.path.join(HERE, "make_dds.py"), os.path.join(src, "loading.jpg"),
        os.path.join(MOD, "data", "ui", "mapthumbnails", "campaign", "cataclysm", f"m{nn}.dds"), "1024", "512")
    run(os.path.join(HERE, "make_shipmap_lua.py"))
    run(os.path.join(HERE, "make_kas_stubs.py"), MOD)
    run(os.path.join(HERE, "luacheck.py"), os.path.join(out, f"m{nn}_kas.lua"),
        os.path.join(MOD, "data", "scripts", "scar", "cataclysmkas_stubs.lua"),
        os.path.join(MOD, "data", "scripts", "scar", "cataclysmkas.lua"))


if __name__ == "__main__":
    main()
