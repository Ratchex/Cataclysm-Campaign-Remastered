"""Build one translated Cataclysm mission into data/leveldata/campaign/cataclysm/m<NN>/:
  m<NN>.level       mission2level.py output (placeholder ships for races not built yet)
  m<NN>_kas.lua     kas2lua.py translation of the mission's code
  m<NN>.lua         wrapper: loads the KAS libraries + runtime + translation, wires OnInit like Gearbox's port
  datfiles.lua, teamcolour.lua (mission2level.py / make_colours.py), and ui/mapthumbnails/campaign/cataclysm/m<NN>.dds (from the loading screen)
Then regenerates the runtime stubs.

Usage: build_mission.py <NN> [--fleet "smt_ms_sp,smt_scout*3,smt_worker*2"] [--background ez01] [--intro n01]
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_modules  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
DECOMP = r"C:\Modding\Cataclysm-decomp"
# Stock HWRM sky per Cataclysm mission (user: use an existing HWRM/HW2RM background, port one only when none fits).
# Matched by rendering Cataclysm's mission<NN>.btg and HW1's ez<NN>.btg (reference/hw1classic/btg) the same way and
# comparing per pixel at every rotation, then by eye: most Cataclysm skies are new art. HWRM can't rotate a sky, so
# Cataclysm's theta (200 for most missions) is lost. Missions not listed: no equivalent yet (decide when we get there).
BACKGROUNDS = {"01": "ez14",      # orange haze, bright core, arc above (ez12 scores the same but has big rings)
               "13": "ez08"}      # HW1's ez08 almost exactly
# Degrees the Kuun-Lan turns left once out of hyperspace (it comes in bow +Z whatever the start point's heading):
# Mission01's faces straight away from the sensor net (user)
ARRIVAL_YAW = {"01": 90}
# Research the player has at the start (user, Mission01: fighter drive, Cataclysm only sells it a little later)
START_RESEARCH = {"01": ["TECH_DRIVE_FIGHTER"]}

WRAPPER = '''-- m{nn}.lua: Cataclysm Mission{nn}, translated from cataclysm.exe (see m{nn}_kas.lua). Generated by build_mission.py.
dofilepath("data:scripts/SCAR/SCAR_Util.lua")
dofilepath("data:scripts/SCAR/KASUtil.lua")
dofilepath("data:scripts/SCAR/SinglePlayerFlow.lua")
dofilepath("data:scripts/SCAR/SinglePlayerNIS.lua")
dofilepath("data:scripts/SCAR/SinglePlayerHyperspace.lua")
dofilepath("data:scripts/SCAR/SpecialFlags.lua")
dofilepath("data:scripts/scar/cataclysmkas_stubs.lua")
dofilepath("data:scripts/scar/cataclysmkas.lua")
dofilepath("data:scripts/scar/cataclysmspeech.lua")
dofilepath("data:scripts/scar/cataclysmships.lua")
dofilepath("data:scripts/scar/cataclysmtech.lua")
dofilepath("data:leveldata/campaign/cataclysm/m{nn}/m{nn}_paths.lua")
dofilepath("data:leveldata/campaign/cataclysm/m{nn}/m{nn}_kas.lua")

-- Kuun-Lan modules at the start (the mission's IncludeShips sMothership<Module>; tools/make_modules.py)
KAS_StartModules = {{ {modules} }}
-- research the player starts with, and the Kuun-Lan's turn on arrival (build_mission.py START_RESEARCH, ARRIVAL_YAW)
KAS_StartResearch = {{ {research} }}
KAS_ArrivalYaw = {yaw}

function OnStartOrLoad()
    print("CATACLYSM Mission{nn}: OnStartOrLoad")
    Sound_SpeechSubtitlePath(KAS_SpeechPath)
end

function OnInit()
    print("CATACLYSM Mission{nn}: OnInit")
    KAS_StartEngine()
    KAS_CreateStartModules()
    KAS_RunAfterIntro("{intro}", Mission{nn}_Start)
end

function Mission{nn}_Start()
    KASRule_Add("Mission{nn}", "Watch_Mission{nn}", "OnInit")
    KAS_Team = "Mission{nn}"
    Init_Mission{nn}("Mission{nn}")
end
'''

DATFILES = '''Dictionaries =
{
\t{
\t\tname = "locale:leveldata/campaign/cataclysm/speech.dat",
\t},
}
'''


def start_modules(src, nn):
    """Kuun-Lan modules the mission starts with: the sMothership<Module> types its .mission includes (Cataclysm
    keeps the Kuun-Lan's modules between missions; the story drops some). One Support module (the count is not
    in the .mission)."""
    keys = []
    for line in open(os.path.join(src, f"mission{nn}.mission"), encoding="latin-1"):
        m = re.match(r"\s*IncludeShips\s+RACE_SECT\s*,\s*sMothership(\w+)", line, re.I)
        if m and m.group(1).lower() in make_modules.MODULES:
            keys.append(make_modules.subsystem(m.group(1).lower()))
    return keys


def run(*args):
    r = subprocess.run([sys.executable, *args], capture_output=True, text=True)
    print(r.stdout.strip())
    if r.returncode:
        print(r.stderr)
        sys.exit(r.returncode)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("nn")
    ap.add_argument("--fleet", default="smt_ms_sp,smt_scout*3,smt_worker*2")
    ap.add_argument("--background", help="default: BACKGROUNDS, else ez01")
    ap.add_argument("--intro", default="", help="cutscene played before the mission starts (e.g. n01)")
    a = ap.parse_args()
    nn = a.nn.zfill(2)
    a.background = a.background or BACKGROUNDS.get(nn, "ez01")
    src = os.path.join(DECOMP, "extracted", "big", "singleplayer", f"mission{nn}")
    out = os.path.join(MOD, "data", "leveldata", "campaign", "cataclysm", f"m{nn}")
    os.makedirs(out, exist_ok=True)
    lvl = ["--shipmap", os.path.join(HERE, "shipmap.tsv"), "--placeholder", "Kus_Scout", "--background", a.background,
           "--player-race", "Somtaaw"]
    if a.fleet:
        lvl += ["--player-fleet", a.fleet]
    lvl += ["--arrival-yaw", str(ARRIVAL_YAW.get(nn, 0))]
    run(os.path.join(HERE, "mission2level.py"), src, os.path.join(out, f"m{nn}.level"), *lvl)
    run(os.path.join(HERE, "kas2lua.py"), DECOMP, f"Mission{nn}", src, os.path.join(out, f"m{nn}_kas.lua"))
    # the teams with a damage factor HWRM's multiplier can't give get weaker weapon copies (make_variants.py)
    run(os.path.join(HERE, "damage_variants.py"), os.path.join(out, f"m{nn}.level"), os.path.join(out, f"m{nn}_kas.lua"))
    # extra ships where HWRM's combat lands a fight differently (level_extras.py)
    run(os.path.join(HERE, "level_extras.py"), nn, os.path.join(out, f"m{nn}.level"))
    with open(os.path.join(out, f"m{nn}.lua"), "w", newline="\n") as f:
        f.write(WRAPPER.format(nn=nn, intro=a.intro, modules=", ".join(f'"{m}"' for m in start_modules(src, nn)),
                               research=", ".join(f'"{t}"' for t in START_RESEARCH.get(nn, [])),
                               yaw=ARRIVAL_YAW.get(nn, 0)))
    run(os.path.join(HERE, "make_colours.py"))   # (teamcolour.lua: written by mission2level.py)
    with open(os.path.join(out, "datfiles.lua"), "w", newline="\n") as f:
        f.write(DATFILES)
    run(os.path.join(HERE, "make_dds.py"), os.path.join(src, "loading.jpg"),
        os.path.join(MOD, "data", "ui", "mapthumbnails", "campaign", "cataclysm", f"m{nn}.dds"), "1024", "512")
    run(os.path.join(HERE, "make_shipmap_lua.py"))
    run(os.path.join(HERE, "make_kas_stubs.py"), MOD)
    run(os.path.join(HERE, "luacheck.py"), os.path.join(out, f"m{nn}_kas.lua"),
        os.path.join(MOD, "data", "scripts", "scar", "cataclysmkas_stubs.lua"),
        os.path.join(MOD, "data", "scripts", "scar", "cataclysmkas.lua"))


if __name__ == "__main__":
    main()
