"""Build Cataclysm speech for the mod from Cataclysm-decomp/out/speech_events_<bank>.tsv (tools/speechmap.py):
  data/sound/speech/missions/cataclysm/<id>.wav   one file per phrase (multi-segment phrases are joined)
  data/locale/english/leveldata/campaign/cataclysm/speech.dat   subtitle per phrase (ends with rangeend); unsubtitled
      phrases get an invisible one (tools/speech_tags.py INVISIBLE: blank ones play nothing in HWRM)
  data/scripts/scar/cataclysmspeech.lua   KAS_SpeechEvent[event] = { nvar, maxvar, base, bank } for the runtime
String/file id = base id of the bank + phrase index (Sect 2200000, Beast 2210000: all below the 22-bit limit).
Phrases are resampled from the decoded 22050 Hz to 44.1 kHz (HWRM plays WAVs at 44.1 kHz regardless of their header).

Usage: build_speech.py [--rate 44100] [--banks sect,beast]
"""
import argparse
import csv
import os
import subprocess
import wave

import speech_tags

DECOMP = r"C:\Modding\Cataclysm-decomp"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFMPEG = r"C:\Modding\ffmpeg\bin\ffmpeg.exe"
BASE = {"sect": 2200000, "beast": 2210000}


def join_wavs(paths, out, rate):
    frames, params = [], None
    for p in paths:
        with wave.open(p) as w:
            params = w.getparams()
            frames.append(w.readframes(w.getnframes()))
    tmp = out + ".tmp.wav"
    with wave.open(tmp if rate != params.framerate else out, "wb") as w:
        w.setparams(params)
        w.writeframes(b"".join(frames))
    if rate != params.framerate:
        subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", tmp, "-ar", str(rate), out], check=True)
        os.remove(tmp)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rate", type=int, default=44100)
    ap.add_argument("--banks", default="sect,beast")
    a = ap.parse_args()
    wav_dir = os.path.join(MOD, "data", "sound", "speech", "missions", "cataclysm")
    dat_dir = os.path.join(MOD, "data", "locale", "english", "leveldata", "campaign", "cataclysm")
    os.makedirs(wav_dir, exist_ok=True)
    os.makedirs(dat_dir, exist_ok=True)
    src = os.path.join(DECOMP, "extracted", "audio", "speech")
    subs, events, written, invisible = {}, {}, 0, 0
    for bank in a.banks.split(","):
        with open(os.path.join(DECOMP, "out", f"speech_events_{bank}.tsv"), encoding="utf-8") as f:
            rows = list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
        for r in rows:
            if not r["files"]:
                continue  # phrase without any recorded segment
            ph, ev = int(r["phrase"]), int(r["event"])
            sid = BASE[bank] + ph
            e = events.setdefault((bank, ev), {"nvar": 0, "maxvar": 0, "base": None, "rows": []})
            e["nvar"] = max(e["nvar"], int(r["variation"]) + 1)
            e["maxvar"] = max(e["maxvar"], int(r["variable"]) + 1)
            e["rows"].append((ph, int(r["variation"]), int(r["variable"])))
            # phrase = base + variation * maxvar + variable: any variation-0 row gives the base (ship-specific
            # events such as Link 156 have no variable-0 row: no line for the Recon)
            if int(r["variation"]) == 0 and (e["base"] is None or ph - int(r["variable"]) < e["base"]):
                e["base"] = ph - int(r["variable"])
            if sid in subs:
                continue
            text = r["subtitle"].strip()
            if not text:
                # a blank subtitle plays nothing in HWRM: empty colour tags count as text but show nothing
                text = speech_tags.INVISIBLE
                invisible += 1
            subs[sid] = (text, int(r["duration_ms"]))
            out = os.path.join(wav_dir, f"{sid}.wav")
            if not os.path.exists(out):
                join_wavs([os.path.join(src, x) for x in r["files"].split(",")], out, a.rate)
                written += 1
    lo, hi = min(BASE.values()), max(BASE.values()) + 9999
    with open(os.path.join(dat_dir, "speech.dat"), "w", encoding="latin-1", newline="\r\n", errors="replace") as f:
        f.write(f"filerange {lo} {hi}\nrangestart {lo} {hi}\n\n// Cataclysm speech subtitles (generated)\n")
        for sid in sorted(subs):
            f.write(f"{sid}\t{subs[sid][0]}\n")
        f.write("\nrangeend\n")
    with open(os.path.join(MOD, "data", "scripts", "scar", "cataclysmspeech.lua"), "w", newline="\n") as f:
        f.write("-- Generated by tools/build_speech.py: speech event -> phrases (HW1 SEselectsentence layout).\n")
        f.write("-- phrase = base + variation * maxvar + variable; string/wav id = KAS_SpeechBankBase[bank] + phrase\n")
        f.write(f'KAS_SpeechBankBase = {{ sect = {BASE["sect"]}, beast = {BASE["beast"]} }}\n')
        f.write("KAS_SpeechEvents = {}\n")
        for (bank, ev), e in sorted(events.items()):
            if e["base"] is None:
                continue
            for ph, var, v in e["rows"]:     # the table's real variable count, when a later variation shows it
                if var > 0 and (ph - e["base"] - v) % var == 0 and (ph - e["base"] - v) // var >= e["maxvar"]:
                    e["maxvar"] = (ph - e["base"] - v) // var
                    break
            f.write(f'KAS_SpeechEvents["{bank}{ev}"] = {{ {e["nvar"]}, {e["maxvar"]}, {e["base"]} }}\n')
        f.write("KAS_SpeechDurations = {}\n")
        for sid in sorted(subs):
            f.write(f"KAS_SpeechDurations[{sid}] = {subs[sid][1]}\n")
    print(f"{len(subs)} phrases ({written} WAVs written), {len(events)} events, {invisible} unsubtitled (invisible subtitle)")


if __name__ == "__main__":
    main()
