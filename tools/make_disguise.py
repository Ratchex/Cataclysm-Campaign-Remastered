"""The pirate corvettes' disguises (Cataclysm kasfShipsDisguise / kasfShipsUndisguise, cataclysm.exe 0x497fd0 /
0x498080: Missions 02, 10 and 12's script-disguised p1StandardCorvette teams) on one ship type,
tur_standardcorvette_disguise: the stock HWRM corvette's Remastered model (its body on joints MimicBody*) plus each
disguise target's Remastered model under a hidden joint Disguise_<n>, one shown at a time by its .madstate (as the
Mimic's, tools/make_mimic.py), in the state the runtime sets (cataclysmkas.lua K_497fd0: KAS_Disguises).

0x497fd0(ships, type, scheme): type a ship type, or "A<n>" an asteroid of type n (FUN_005b8d70 mode 2); scheme the
colour scheme it is drawn in (here baked into the target's diffuse where its team map paints, tools/hod2dae.py).

  make_disguise.py --dae      build/ships/<NAME>/<NAME>.dae (tools/hod2dae.py)
  make_disguise.py --install  data/ship/<NAME>/ (.hod from HODOR, our tur_standardcorvette.ship, stock .events,
                              .madstate, a still .mad) and data/scripts/scar/cataclysmdisguise_gen.lua
Usage: tools/build_disguise.sh (Git Bash: HODOR)
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
REF = r"C:/Modding/Cataclysm-decomp/reference"
NAME = "tur_standardcorvette_disguise"
BASE = "tur_standardcorvette"
BODY = "MimicBody"
BODY_HOD = f"{REF}/hwrm/Homeworld2/ship/{BASE}/{BASE}.hod"
# (Cataclysm type as the mission passes it, colour scheme) -> Remastered model (Gearbox's substitutes as shipmap.tsv)
TARGETS = [
    ("kadvancesupportfrigate", 0, f"{REF}/hwrm/HW1Ships/ship/kus_supportfrigate/kus_supportfrigate.hod"),   # M02
    ("djunk3boiler", 2, f"{REF}/hwrm/Homeworld2/ship/der_junk3_boiler/der_junk3_boiler.hod"),              # M10
    ("djunk2shipwreck", 2, f"{REF}/hwrm/Homeworld2/ship/der_junk2_shipwreck/der_junk2_shipwreck.hod"),
    ("djunk1shell", 2, f"{REF}/hwrm/Homeworld2/ship/der_junk1_shell/der_junk1_shell.hod"),
    ("djunk1parta", 2, f"{REF}/hwrm/Homeworld2/ship/der_junk1_parta/der_junk1_parta.hod"),
    ("tresourcecollector", 3, f"{REF}/hwrm/HW1Ships/ship/tai_resourcecollector/tai_resourcecollector.hod"),
    ("a1", 0, f"{REF}/hwrm/Homeworld2/resource/asteroid/asteroid1/asteroid1.hod"),                          # M12
    ("sacolyte", 0, os.path.join(MOD, "build", "ships", "som_acolyte", "som_acolyte.hod")),   # ours (build_ship.sh)
    ("p1fighter", 5, f"{REF}/hwrm/Homeworld2/ship/tur_fighter/tur_fighter.hod"),
]
STATES = ["NIS01", "NIS02"] + [f"DockPathOpen{n}" for n in range(1, 6)] + [f"DockPathClosed{n}" for n in range(1, 6)]
OUT = os.path.join(MOD, "build", "ships", NAME)
SHIP_DIR = os.path.join(MOD, "data", "ship", NAME)


def joint(k):
    return f"Disguise_{TARGETS[k][0]}_{TARGETS[k][1]}"


def dae():
    assert len(TARGETS) <= len(STATES), "more disguises than mad states"
    # collision from the corvette alone (user: shots hit the disguise's outline, HODOR's took in every disguise)
    args = [sys.executable, os.path.join(HERE, "hod2dae.py"), OUT, NAME, "--body", BODY_HOD, "--body-joint", BODY,
            "--col-slices", "10"]
    for k, (_, scheme, hod) in enumerate(TARGETS):
        args += ["--part", f"{joint(k)}@{hod}@{scheme}"]
    subprocess.check_call(args)


def madstate():
    body = [l for l in open(os.path.join(OUT, "bodyjoints.txt")).read().split() if l]
    up = NAME.upper()
    names = body + [joint(k) for k in range(len(TARGETS))]
    lines = ["-- Generated by tools/make_disguise.py: the pirate corvette's body and its disguises (joints of its model),",
             "-- one shown at a time: NIS00 the corvette, NIS01... a disguise (cataclysmkas.lua K_497fd0 / K_498080).",
             f"{up}_Show = function(ship, shown)"]
    for n in names:
        on = f'shown == "{BODY}"' if n in body else f'shown == "{n}"'
        lines.append(f'    if({on}) then setJointVisible(ship, "{n}", 1) else setJointVisible(ship, "{n}", 0) end')
    lines += ["end", "", f"{up}_NIS00_OnSet = function(ship)", f'    {up}_Show(ship, "{BODY}")', "end"]
    for k in range(len(TARGETS)):
        lines += ["", f"{up}_{STATES[k]}_OnSet = function(ship)", f'    {up}_Show(ship, "{joint(k)}")', "end"]
    return "\n".join(lines) + "\n", names


def install():
    os.makedirs(SHIP_DIR, exist_ok=True)
    shutil.copyfile(os.path.join(OUT, NAME + ".hod"), os.path.join(SHIP_DIR, NAME + ".hod"))
    ship = open(os.path.join(MOD, "data", "ship", BASE, BASE + ".ship"), encoding="latin-1").read()
    # one LOD (hod2dae writes LOD 0 only): the stock LOD distances left our one-LOD models invisible zoomed out
    ship = re.sub(r"^\s*NewShipType\.(upLOD|downLOD)\s*=.*\n", "", ship, flags=re.M)
    ship = re.sub(r"^(\s*NewShipType\.minLOD\s*=\s*)[\d.]+", r"\g<1>1", ship, flags=re.M)
    with open(os.path.join(SHIP_DIR, NAME + ".ship"), "w", encoding="latin-1", newline="\n") as f:
        f.write(f"-- {NAME}: {BASE} with Cataclysm's script disguises on its model (tools/make_disguise.py)\n" + ship)
    shutil.copyfile(f"{REF}/hwrm/Homeworld2/ship/{BASE}/{BASE}.events", os.path.join(SHIP_DIR, NAME + ".events"))
    text, names = madstate()
    with open(os.path.join(SHIP_DIR, NAME + ".madstate"), "w", newline="\n") as f:
        f.write(text)
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_static_mad.py"), os.path.join(SHIP_DIR, NAME + ".mad")]
                          + names)
    lua = os.path.join(MOD, "data", "scripts", "scar", "cataclysmdisguise_gen.lua")
    with open(lua, "w", newline="\n") as f:
        f.write("-- Generated by tools/make_disguise.py: kasfShipsDisguise(type, scheme) -> the disguise ship type's mad "
                "state\n")
        f.write(f'KAS_DisguiseType = "{NAME}"\nKAS_Disguises = {{\n')
        for k, (t, scheme, _) in enumerate(TARGETS):
            f.write(f'    ["{t}@{scheme}"] = "{STATES[k]}",\n')
        f.write("}\n")
    print(f"{SHIP_DIR}: {len(TARGETS)} disguises; {lua}")


if __name__ == "__main__":
    if "--dae" in sys.argv:
        dae()
    elif "--install" in sys.argv:
        install()
    else:
        sys.exit(__doc__)
