"""Cataclysm ship abilities on HWRM's command panel (Cataclysm's Special menu: Link, Unlink, Fire Missiles, EMP,
...). HWRM keeps one CustomCommand per ship (a second replaces the first: tested), so an ability is either
  native: the ship's CustomCommand (ui/newui/commanduidefines.lua INFO_CustomStart + id, stock uses 0-3): the engine
    shows its button and right-click entry, sends it to the selected ships that have it, and draws its energy bar
    (Cataclysm's cooldowns, e.g. the Acolyte's missile volley). One per ship type.
  button: a taskbar button of ours running MainUI_ScarEvent("CatAbility('<name>')"): the mission script puts the
    human's selection in SobGroup "cat_cmd_<name>" and shows the button while the selection can use it
    (cataclysmkas.lua CatAbilityTick); each ship acts if it is in the group and still selected (shiprules.lua).
    No right-click entry (the engine builds that menu).

Writes:
  data/ui/newui/taskbar/cat_abilities.lua   the buttons
  data/ui/newui/newtaskbar.lua              stock HWRM's, with the buttons in "specialButtons"
  data/ui/newui/commanduidefines.lua        stock HWRM's, with the native abilities' buttons and right-click names
  data/scripts/cataclysm/abilities_gen.lua  CatAbilities, for the ship rules and the mission script

Usage: make_abilities.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_upgrades  # noqa: E402
import ship_variants  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.dirname(HERE)
STOCK_UI = r"C:\Modding\Cataclysm-decomp\reference\hwrm\Homeworld2\ui\newui"
ICONS = "DATA:UI\\\\NewUI\\\\Taskbar\\\\CommandIcons\\\\"

# name: (command ID 4-31 if native else None, label, ship types, research to show the button ("" none), upgrade
# the ship must have ("" none: tools/make_upgrades.py), handler in shiprules.lua, icon).
# Labels: english.script strMenuSpecial*Desc. Icons: stock placeholders for now.
ABILITIES = {
    # the Acolyte's native command is its missile volley (strMenuSpecialFireMissilesDesc): its energy bar is the
    # missile cooldown (ENERGY); Link is a button
    "volley": (6, "Fire Missiles", ["smt_acolyte"], "", "ORDINANCE", "CatVolley_Start", "cmd_ico_missilevolley.dds"),
    "link": (None, "Link", ["smt_acolyte"], "TECH_LINK", "LINK", "CatLink_Start", "cmd_ico_dronefrigate.dds"),
    "unlink": (None, "Unlink", ["smt_acv"], "", "UNLINK", "CatUnlink_Start", "cmd_ico_specialattack.dds"),
    # strMenuUpgradeSectShipsDesc: every ship type with upgrades
    "upgrade": (None, "Upgrade", make_upgrades.upgradable(), "", "", "CatUpgrade_Start", "cmd_ico_repair.dds"),
    # the Mimic (strMenuSpecialSelectMimicTypeDesc "Select Mimic Type"): "mimic" opens a menu of disguises (one
    # button each, MENU below), "unmimic" drops the disguise (ship_variants.py DISGUISES, shiprules.lua CatMimic_*)
    "mimic": (None, "Mimic", ["smt_mimic"], "", "MIMIC", "CatNoop", "cmd_ico_cloak.dds"),
    "unmimic": (None, "Unmimic", sorted(ship_variants.DISGUISES), "", "", "CatUnmimic_Start", "cmd_ico_cancel.dds"),
}
# disguise buttons, shown while the Mimic menu is open (a placeholder icon each: stock command icons)
DISGUISE_ICONS = ["cmd_ico_attack.dds", "cmd_ico_burstattack.dds", "cmd_ico_defense.dds", "cmd_ico_moveatk.dds",
                  "cmd_ico_speedburst.dds", "cmd_ico_custom.dds", "cmd_ico_dronefrigate.dds", "cmd_ico_misc.dds"]
MENU = {}       # ability -> the menu it is in ("mimic": shown only while the Mimic menu is open)
for k, (variant, (_, target, label, _)) in enumerate(sorted(ship_variants.DISGUISES.items())):
    ABILITIES[f"mimic_{target}"] = (None, f"Mimic: {label}", ["smt_mimic"], "", "MIMIC", "CatMimic_As",
                                    DISGUISE_ICONS[k % len(DISGUISE_ICONS)])
    MENU[f"mimic_{target}"] = "mimic"
OPENS = {"mimic": "mimic"}   # ability -> the menu its button opens / closes (no ship action)

# A native ability's energy (CustomCommand: max, minimum to activate, drain, recharge per second), the bar the engine
# draws beside the health bar. Default: no cooldown (drains and refills at once). A cooldown ability drains at once
# and refills over its cooldown. The volley: Cataclysm's Acolyte carries 2 missiles (sacolyte.shp GUN2/GUN3,
# MaxMissiles 1), one regenerating every MissileRegenerateTime 10.375 s (FUN_005b0f10): full (2) in 20.75 s. The engine
# spends the minimum to activate on a press. (Not modelled: no regeneration for MissileLagVolleyTime 12 s after a volley.)
INSTANT = (1000, 0, 1000, 1000)
ENERGY = {
    "volley": (1000, 1000, 1000, round(1000 / (2 * 10.375), 1)),   # a volley spends the whole bar (both missiles)
}


def energy(name):
    return ENERGY.get(name, INSTANT)


def main():
    ui = ["-- Generated by tools/make_abilities.py: Cataclysm ability buttons (GetCommandButton: TB_CommandPanel.lua)"]
    for name, (cid, label, _, _, _, _, icon) in ABILITIES.items():
        if cid is not None:
            click = (f'"MainUI_UserEventData( eCustomActivate, {cid} );", '
                     f'"MainUI_UserEventData( eCustomDeActivate, {cid} );"')
        else:
            click = '"MainUI_ScarEvent( \\"CatAbility(\'%s\')\\" )"' % name
        ui.append(f'CAT_BTN_{name.upper()} = GetCommandButton("btnCat_{name}", "{label}", nil, "{ICONS}{icon}", {click})')
        if cid is None:
            # a script button has no energy: GetCommandButton's CooldownFrame child would draw its placeholder
            # (cooldownProgress 24 of 100: a number and a fifth of the button shaded, user); removed. Native ones
            # keep it (their energy bar)
            ui.append(f"CAT_BTN_{name.upper()}[1] = nil")
    folder = os.path.join(MOD, "data", "ui", "newui", "taskbar")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "cat_abilities.lua"), "w", newline="\n") as f:
        f.write("\n".join(ui) + "\n")

    text = open(os.path.join(STOCK_UI, "newtaskbar.lua"), encoding="latin-1").read()
    inc = 'dofilepath("data:ui/newui/Taskbar/TB_CommandPanel.lua")'
    anchor = "\t\t\t\tBTN_CMD_CAPTURE,"
    assert inc in text and anchor in text
    text = text.replace(inc, inc + '\ndofilepath("data:ui/newui/taskbar/cat_abilities.lua")   -- Cataclysm-HWRM', 1)
    text = text.replace(anchor, anchor + "\n\t\t\t\t-- Cataclysm-HWRM abilities (tools/make_abilities.py)\n" +
                        "".join(f"\t\t\t\tCAT_BTN_{n.upper()},\n" for n in ABILITIES), 1)
    with open(os.path.join(MOD, "data", "ui", "newui", "newtaskbar.lua"), "w", encoding="latin-1", newline="") as f:
        f.write("-- Stock HWRM newtaskbar.lua with Cataclysm's ability buttons (tools/make_abilities.py)\n" + text)

    text = open(os.path.join(STOCK_UI, "commanduidefines.lua"), encoding="latin-1").read().rstrip()
    assert text.endswith("}")
    entries = "".join(f'    -- Cataclysm-HWRM (tools/make_abilities.py)\n    {{\n        commandID = INFO_CustomStart + {cid},\n'
                      f'        activateButtonName = "btnCat_{name}",\n        rightClickDisplayName = "{label}",\n    }},\n'
                      for name, (cid, label, _, _, _, _, _) in ABILITIES.items() if cid is not None)
    text = text[:-1] + entries + "}\n"
    with open(os.path.join(MOD, "data", "ui", "newui", "commanduidefines.lua"), "w", encoding="latin-1",
              newline="") as f:
        f.write("-- Stock HWRM commanduidefines.lua with Cataclysm's abilities (tools/make_abilities.py)\n" + text)

    gen = ["-- Generated by tools/make_abilities.py: Cataclysm abilities (custom command INFO_CustomStart + id)",
           "CatAbilities = {"]
    for name, (cid, label, types, tech, upgrade, handler, _) in ABILITIES.items():
        # with their variants and disguises (tools/ship_variants.py): the mission script shows buttons by type
        types = types + [v for v in list(ship_variants.VARIANTS) + list(ship_variants.DISGUISES)
                         if ship_variants.base_of(v) in types and v not in types]
        gen.append(f'    {{ name = "{name}", native = {0 if cid is None else 1}, label = "{label}", '
                   f'types = "{", ".join(types)}", tech = "{tech}", upgrade = "{upgrade}", handler = "{handler}", '
                   f'menu = "{MENU.get(name, "")}", opens = "{OPENS.get(name, "")}" }},')
    gen.append("}")
    with open(os.path.join(MOD, "data", "scripts", "cataclysm", "abilities_gen.lua"), "w", newline="\n") as f:
        f.write("\n".join(gen) + "\n")
    print(f"{len(ABILITIES)} abilities: {', '.join(ABILITIES)}")


def for_ship(ship):
    """(name, id, label) of the native ability a ship type has (at most one: HWRM keeps one CustomCommand); a
    variant has its base's (tools/ship_variants.py)."""
    import ship_variants
    ship = ship_variants.base_of(ship)
    native = [(n, a[0], a[1]) for n, a in ABILITIES.items() if ship in a[2] and a[0] is not None]
    assert len(native) <= 1, f"{ship}: more than one native ability {native}"
    return native


if __name__ == "__main__":
    main()
