"""Effects for the Somtaaw Worker (Cataclysm's harvest and repair cones) -> data/art/fx/.

Cataclysm draws both as etg/meshes/resource/cone.geo with an additive tint (etg/general.script):
  EGT_WORKER_RESOURCE_SOLID = SectBeast_resource_solid.ebg  setAddColor(1.0, 0.4, 0.0)   orange harvest cone
  EGT_REPAIR_BEAM           = Repair_Corvette.ebg           setAddColor(0.1, 0.5, 0.0)   green repair cone
Here: HWRM's own HW1 harvest cone (stock harvesting_beam_kus.lua, mesh FX_HARVESTKUS.HOD, sized for a collector
holding 400 units off) with Cataclysm's tint (scaled so the brightest channel is 1), and for harvesting the stock
burn rings / spray around it (harvesting_beam_kus_combo without its cone).

Usage: make_worker_fx.py
"""
import os
import re

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STOCK = r"C:\Modding\Cataclysm-decomp\reference\hwrm\Homeworld2\art\fx"
OUT = os.path.join(MOD, "data", "art", "fx")

CONES = {   # fx name -> Cataclysm additive colour
    "som_harvest_cone": (1.0, 0.4, 0.0),
    "som_repair_cone": (0.2, 1.0, 0.0),
}
HARVEST_COMBO = ["SOM_HARVEST_CONE", "HARVESTING_BEAM_BURN_RING", "HARVESTING_BEAM_BURN_RING02",
                 "HARVESTING_BEAM_SPRAY", "HARVESTING_BEAM_TUBE_SPRAY"]


def colour_block(rgb):
    r, g, b = rgb
    return ('name = "Colour",\ntype = "VARTYPE_ARRAY_TIMECOLOUR",\nvalue = {\n'
            f'entry_00 = {{\n0,\n{r},\n{g},\n{b},\n1,\n}},\n'
            f'entry_01 = {{\n1,\n{r},\n{g},\n{b},\n1,\n}},\n}},')


def main():
    os.makedirs(OUT, exist_ok=True)
    src = open(os.path.join(STOCK, "harvesting_beam_kus.lua"), encoding="latin-1").read().replace("\r\n", "\n")
    pat = re.compile(r'name = "Colour",\ntype = "VARTYPE_ARRAY_TIMECOLOUR",\nvalue = \{\n(?:entry_\d+ = \{[^}]*\},\n)+\},')
    if len(pat.findall(src)) != 1:
        raise SystemExit("stock harvesting_beam_kus.lua: Colour property not found")
    for name, rgb in CONES.items():
        text = "-- Generated by tools/make_worker_fx.py (stock harvesting_beam_kus.lua, Cataclysm's tint)\n"
        text += pat.sub(lambda m: colour_block(rgb), src)
        open(os.path.join(OUT, name + ".lua"), "w", encoding="latin-1", newline="\n").write(text)
    props = "".join(f'property_{i:02d} = {{\nname = "FX{i + 1}",\ntype = "VARTYPE_STRING",\nvalue = "{fx}",\n}},\n'
                    for i, fx in enumerate(HARVEST_COMBO))
    open(os.path.join(OUT, "som_harvest_combo.lua"), "w", encoding="latin-1", newline="\n").write(
        "-- Generated by tools/make_worker_fx.py\nfx = {\nstyle = \"STYLE_COMBO\",\nproperties = {\n" + props + "},\n}\n")
    print(f"{len(CONES) + 1} effects in {OUT}")


if __name__ == "__main__":
    main()
