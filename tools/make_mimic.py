"""The Mimic's model and its states: Cataclysm's Mimic shows its target's model on itself (FUN_005b9640: the
mimicked type's model while mimicking), the same ship flying on. Here its model (som_mimic, tools/build_mimic.sh)
holds its own body (joint MimicBody) and every disguise target's Cataclysm model (joint Disguise_<target>, painted in
that target's faction colours: a team colour scheme would repaint the whole ship), one shown at a time by
its .madstate (setJointVisible), in the state shiprules.lua sets (SobGroup_SetMadState: NIS00 the Mimic, NIS01...
each disguise, ship_variants.disguise_states).

  --list-parts   the geo2dae.py --part specs (for tools/build_mimic.sh)
  (default)      tools/overrides/ship/smt_mimic/smt_mimic.madstate, build/ships/som_mimic/som_mimic.mad (one still
                 clip: the madstate never ran without a .mad)

Usage: tools/build_mimic.sh
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_colours  # noqa: E402
import ship_variants  # noqa: E402
from make_mimicfx import CATACLYSM_MODEL  # noqa: E402

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIG = "C:/Modding/Cataclysm-decomp/extracted/big"
BODY = "MimicBody"


def targets():
    """[(target, colour scheme)] in state order (NIS01...)."""
    states = ship_variants.disguise_states()
    return sorted(((t, sc) for _, t, _, sc in ship_variants.DISGUISES.values()), key=lambda x: states[x[0]])


def joint(target):
    return f"Disguise_{target}"


def parts():
    schemes = make_colours.read()
    out = []
    for t, sc in targets():
        model = CATACLYSM_MODEL[t]
        rgb = lambda c: ",".join(str(round(v * 255)) for v in c)
        s = schemes[sc]
        out.append(f"{joint(t)}@{BIG}/{model}/rl0/lod0/{os.path.basename(model)}.geo@{rgb(s['BaseColor'])}"
                   f"@{rgb(s['StripeColor'])}")
    return out


def madstate():
    names = [BODY] + [joint(t) for t, _ in targets()]
    states = ship_variants.disguise_states()
    lines = ["-- Generated by tools/make_mimic.py: the Mimic's body and its disguises (joints of its model), one shown",
             "-- at a time. SobGroup_SetMadState passes on only the engine's state names (custom names never reached",
             "-- the madstate): NIS00 the Mimic, NIS01... its disguises (shiprules.lua CatMimic_*).",
             "SMT_MIMIC_Show = function(ship, shown)"]
    for n in names:
        lines.append(f'    if(shown == "{n}") then setJointVisible(ship, "{n}", 1) else setJointVisible(ship, "{n}", 0) end')
    lines += ["end", "", f'SMT_MIMIC_NIS00_OnSet = function(ship)', f'    SMT_MIMIC_Show(ship, "{BODY}")', "end"]
    for t, _ in targets():
        lines += ["", f"SMT_MIMIC_{states[t]}_OnSet = function(ship)", f'    SMT_MIMIC_Show(ship, "{joint(t)}")', "end"]
    return "\n".join(lines) + "\n", names


def main():
    if "--list-parts" in sys.argv:
        print(" ".join(parts()))
        return
    text, names = madstate()
    path = os.path.join(MOD, "tools", "overrides", "ship", "smt_mimic", "smt_mimic.madstate")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(text)
    subprocess.check_call([sys.executable, os.path.join(MOD, "tools", "make_static_mad.py"),
                           os.path.join(MOD, "build", "ships", "som_mimic", "som_mimic.mad")] + names)
    print(f"{path}: {len(names) - 1} disguises")


if __name__ == "__main__":
    main()
