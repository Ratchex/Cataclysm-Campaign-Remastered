def main():
    for n in range(5):
        shp = open(os.path.join(CAT, f"asteroid{n}.shp"), encoding="latin-1").read()
        health = int(float(re.search(r"^maxhealth\s+([\d.]+)", shp, re.M | re.I).group(1)))
        name = f"cat_meteor{n}"
        d = os.path.join(MOD, "data", "ship", name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name + ".ship"), "w", newline="\n") as f:
            f.write(SHIP.format(n=n, health=health, speed=MAX_SPEED))
        shutil.copyfile(os.path.join(REF, f"asteroid{n}", f"asteroid{n}.hod"), os.path.join(d, name + ".hod"))
        print(f"{name}: health {health}")


if __name__ == "__main__":
    main()
