"""Single-player build and research lists for the Somtaaw race of Cataclysm Remastered (tools/install_cr.py).

Their race and ships are used as they are; for the campaign the build list and research tree are Cataclysm's:
  races/somtaaw/scripts/sp_build.lua     every Somtaaw ship mapped in shipmap.tsv, gated by SPRSShipDepend
  races/somtaaw/scripts/sp_research.lua  every SPRSTECH_* tech: Time = Cataclysm's research seconds (HW1
                                         ResearchAPI.c TimeToComplete), prerequisites from SPRSTechDepend ("&"),
                                         TargetName = first ship it unlocks; Cost: see COST_PER_SECOND
  scripts/scar/cataclysmtech.lua         KAS_Techs, for kasfAllowPlayerToResearch/Purchase gating
(their singleplayer/props/gbx.lua points path_build/path_research here: install_cr.py patch)

Usage: make_race.py
"""
import csv
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_modules  # noqa: E402

DECOMP = r"C:\Modding\Cataclysm-decomp"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RACE = os.path.join(MOD, "data", "scripts", "races", "somtaaw")

# Cataclysm charges RUs for research, but the price is not in its data files. Provisional until found in the exe.
COST_PER_SECOND = 10


def read_research():
    techs, tech_dep, ship_dep = {}, {}, {}
    for line in open(os.path.join(DECOMP, "extracted", "big", "researchdepend.script"), encoding="latin-1"):
        line = line.split(";")[0].strip()
        m = re.match(r"SPRS(TECH_\w+)\s+(\d+)", line)
        if m:
            techs[m.group(1)] = int(m.group(2))
            continue
        m = re.match(r"SPRS(Ship|Tech)Depend\s+(\w+)\s+(.*)", line)
        if m:
            deps = [d.strip() for d in m.group(3).split(",") if d.strip()]
            (ship_dep if m.group(1) == "Ship" else tech_dep)[m.group(2).lower()] = deps
    return techs, tech_dep, ship_dep


HANGAR = make_modules.MODULES["dockingbay"][2]   # ships need the Hangar module (Cataclysm: "We need a hangar module")
# (research name, ship, engine ability it grants): see the research list's end
RUNTIME_RESEARCH = [("CAT_ACOLYTE_MISSILES", "smt_acolyte", "UseSpecialWeaponsInNormalAttack")]


def module_of(tech):
    """RequiredSubSystems: the typeString of the module that researches the tech, else any research subsystem."""
    key = make_modules.TECH_MODULE.get(tech)
    return make_modules.MODULES[key][2] if key else "Research"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write(text)


def main():
    techs, tech_dep, ship_dep = read_research()
    rows = csv.DictReader(open(os.path.join(MOD, "tools", "shipmap.tsv"), encoding="utf-8"), delimiter="\t")
    ships = [(r["ship"].lower(), r["hwrm"]) for r in rows
             if r["race"] == "RACE_SECT" and r["hwrm"] and not r["ship"].lower().startswith("smothership")]

    b = ["-- Generated by tools/make_race.py: Somtaaw ships (Cataclysm Remastered) with Cataclysm's research gates.",
         "Ship = 0", "SubSystem = 1", "build =", "{"]
    for prio, (cat, ship) in enumerate(ships):
        req = " & ".join(ship_dep.get(cat, []))
        name = ship.split("_", 1)[1].title()
        b += ["\t{", "\t\tType =\t\t\t\t\tShip,", f'\t\tThingToBuild =\t\t\t"{ship}",',
              f'\t\tRequiredResearch =\t\t"{req}",',
              f'\t\tRequiredShipSubSystems =\t"{"" if ship == "smt_worker" else HANGAR}",',
              f"\t\tDisplayPriority =\t\t{10 + prio},", f'\t\tDisplayedName =\t\t\t"{name}",',
              f'\t\tDescription =\t\t\t"{name}",', "\t},"]
    structural = []
    for prio, (key, (_, disp, _, _, buildable, tech)) in enumerate(make_modules.MODULES.items()):
        # every Kuun-Lan module must be in the build list, or SobGroup_CreateSubSystem refuses it ("Race Specific
        # subsystem"); the structural ones (not in Cataclysm's build manager) are restricted by the mission runtime
        # once the starting modules exist (KAS_StructuralModules, cataclysmkas.lua)
        if not buildable:
            structural.append(make_modules.subsystem(key))
        b += ["\t{", "\t\tType =\t\t\t\t\tSubSystem,", f'\t\tThingToBuild =\t\t\t"{make_modules.subsystem(key)}",',
              f'\t\tRequiredResearch =\t\t"{tech}",', '\t\tRequiredShipSubSystems =\t"",',
              f"\t\tDisplayPriority =\t\t{100 + prio},", f'\t\tDisplayedName =\t\t\t"{disp}",',
              f'\t\tDescription =\t\t\t"{disp}",', "\t},"]
    write(os.path.join(RACE, "scripts", "sp_build.lua"), "\n".join(b + ["}", ""]))

    converted = dict(ships)
    r = ["-- Generated by tools/make_race.py from researchdepend.script (SPRS* = single player).",
         'Icon_Tech = "data:ui/newui/research/icons/tech.mres"',
         'Icon_Build = "data:ui/newui/research/icons/build.mres"', "Modifier = 0", "Ability = 1", "AllShips = 0",
         "Family = 1", "Ship = 2", "research =", "{"]
    for i, (t, secs) in enumerate(sorted(techs.items())):
        req = " & ".join(tech_dep.get(t.lower(), []))
        unlocks = [converted[c] for c, deps in ship_dep.items() if t in deps and c in converted]
        title = t[5:].replace("_", " ").title()
        r += ["\t{", f'\t\tName =\t\t\t\t"{t}",', f'\t\tRequiredResearch =\t"{req}",',
              f'\t\tRequiredSubSystems =\t"{module_of(t)}",', f"\t\tCost =\t\t\t\t{secs * COST_PER_SECOND},",
              f"\t\tTime =\t\t\t\t{secs},", f'\t\tDisplayedName =\t\t"{title}",', f'\t\tShortDisplayedName =\t"{title}",',
              f"\t\tDisplayPriority =\t{10 + i},", f'\t\tDescription =\t\t"{title}",',
              f"\t\tIcon =\t\t\t\t{'Icon_Build' if unlocks else 'Icon_Tech'},",
              f'\t\tTargetName =\t\t"{unlocks[0] if unlocks else "smt_ms_sp"}",', "\t},"]
    # not Cataclysm research: engine abilities our upgrade system switches per ship (shiprules.lua), granted at
    # mission start (cataclysmkas.lua KAS_GrantRuntimeResearch). The Acolyte's missile launchers are "Special Attack"
    # weapons that fire in normal attacks only while UseSpecialWeaponsInNormalAttack is on.
    for name, ship, ability in RUNTIME_RESEARCH:
        r += ["\t{", f'\t\tName =\t\t\t\t"{name}",', '\t\tRequiredResearch =\t"",', '\t\tRequiredSubSystems =\t"",',
              "\t\tCost =\t\t\t\t0,", "\t\tTime =\t\t\t\t1,", f'\t\tDisplayedName =\t\t"{name}",',
              f'\t\tShortDisplayedName =\t"{name}",', "\t\tDisplayPriority =\t999,", f'\t\tDescription =\t\t"{name}",',
              "\t\tUpgradeType =\t\tAbility,", "\t\tTargetType =\t\tShip,", f'\t\tTargetName =\t\t"{ship}",',
              f'\t\tUpgradeName =\t\t"{ability}",', "\t\tIcon =\t\t\t\tIcon_Tech,", "\t},"]
    write(os.path.join(RACE, "scripts", "sp_research.lua"), "\n".join(r + ["}", ""]))

    write(os.path.join(MOD, "data", "scripts", "scar", "cataclysmtech.lua"),
          "-- Generated by tools/make_race.py: Cataclysm single-player techs (research option names).\n"
          "KAS_Techs = {" + ", ".join(f'"{t}"' for t in sorted(techs)) + "}\n"
          "-- Kuun-Lan modules the player can never build (restricted after the starting modules are created)\n"
          "KAS_StructuralModules = {" + ", ".join(f'"{s}"' for s in structural) + "}\n")
    print(f"Somtaaw SP lists: {len(ships)} ships, {len(techs)} techs")


if __name__ == "__main__":
    main()
