"""Generate the Somtaaw race (data/scripts/races/somtaaw*) from Cataclysm's researchdepend.script.

  races/somtaaw.lua                      race definition (prefix SOM_, like Som_Mothership)
  races/somtaaw/props/default.lua        Kushan's props with Somtaaw paths and mothership type
  races/somtaaw/singleplayer/...         SP props (sp_build/sp_research) and unit caps (Kushan's for now)
  races/somtaaw/scripts/{sp,def}_build.lua      ships built so far (BUILD below) with Cataclysm's tech gates
  races/somtaaw/scripts/{sp,def}_research.lua   every SPRSTECH_* tech: Time = Cataclysm's research seconds,
                                                prerequisites from SPRSTechDepend ("&"); Cost: see COST_PER_SECOND
  scripts/scar/cataclysmtech.lua         KAS_Techs (all tech names) for kasfAllowPlayerToResearch/Purchase gating
Kushan files that only feed skirmish AI (ai_*.lua, crate_*.lua) are copied unchanged so the props paths resolve.

Usage: make_race.py
"""
import os
import re
import shutil

DECOMP = r"C:\Modding\Cataclysm-decomp"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KUS = os.path.join(DECOMP, "reference", "hwrm", "Homeworld2", "scripts", "races", "kushan")
RACES = os.path.join(MOD, "data", "scripts", "races")

# Cataclysm charges RUs for research, but the price is not in its data files (researchdepend.script only has
# times; HW1's ResearchAPI.c reads them as TimeToComplete). Provisional until found in the exe.
COST_PER_SECOND = 10

BUILD_FAMILIES = ["Fighter", "Corvette", "Frigate", "Resource", "NonCombat", "SubSystem"]

# Ships built so far: (ship, Cataclysm type for researchdepend lookups, display priority)
BUILD = [("Som_Worker", "sWorker", 10), ("Som_Recon", "sRecon", 11), ("Som_Acolyte", "sAcolyte", 12)]


def read_research():
    techs, tech_dep, ship_dep = {}, {}, {}
    for line in open(os.path.join(DECOMP, "extracted", "big", "researchdepend.script"), encoding="latin-1"):
        line = line.split(";")[0].strip()
        m = re.match(r"SPRS(TECH_\w+)\s+(\d+)", line)
        if m:
            techs[m.group(1)] = int(m.group(2))
            continue
        m = re.match(r"SPRS(Ship|Tech)Depend\s+(\w+)\s+(.*)", line)
        if m:
            deps = [d.strip() for d in m.group(3).split(",") if d.strip()]
            (ship_dep if m.group(1) == "Ship" else tech_dep)[m.group(2).lower()] = deps
    return techs, tech_dep, ship_dep


def tech_title(t):
    return t[5:].replace("_", " ").title()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="latin-1", newline="\n") as f:
        f.write(text)


def main():
    techs, tech_dep, ship_dep = read_research()
    # Kushan's filter tags: the single-player race filter only accepts races with these (else "Unknown Race").
    kus = open(os.path.join(os.path.dirname(KUS), "kushan.lua"), encoding="latin-1").read()
    tags = "\n".join(l for l in kus.splitlines() if l.startswith(("ExtFilter", "Tags")))
    write(os.path.join(RACES, "somtaaw.lua"),
          'Path_Name = "Somtaaw"\nSymbolic_Name = "Somtaaw"\nDisplay_Name = "Somtaaw"\nPrefix = "SOM_"\n\n'
          + tags + '\n\nSG_Pass_Tags = "sgf_common,sgf_kus"\n')
    # Build families must be declared in scripts/familylist.lua: the stock list plus the Somtaaw ones.
    fam = open(os.path.join(os.path.dirname(os.path.dirname(KUS)), "familylist.lua"), encoding="latin-1").read()
    anchor = '\t{\n\t\tname = "Fighter_Kus",\n\t},\n'
    assert anchor in fam, "familylist.lua layout changed"
    extra = "".join(f'\t{{\n\t\tname = "{f}_Som",\n\t}},\n' for f in BUILD_FAMILIES)
    write(os.path.join(MOD, "data", "scripts", "familylist.lua"),
          "-- Stock familylist.lua plus the Somtaaw build families (tools/make_race.py).\n"
          + fam.replace(anchor, extra + anchor, 1))
    props = open(os.path.join(KUS, "props", "default.lua"), encoding="latin-1").read()
    props = props.replace("races/kushan/", "races/somtaaw/").replace('"kus_mothership"', '"som_mothership"')
    write(os.path.join(RACES, "somtaaw", "props", "default.lua"), "-- Generated by tools/make_race.py from Kushan's.\n" + props)
    write(os.path.join(RACES, "somtaaw", "singleplayer", "props", "gbx.lua"),
          '-- Somtaaw\n\nString_Properties_Priority = 1.0\n\nString_Properties = {\n'
          '\tpath_build = [[data:scripts/races/somtaaw/scripts/sp_build.lua]],\n'
          '\tpath_research = [[data:scripts/races/somtaaw/scripts/sp_research.lua]],\n}\n')
    for rel in (os.path.join("singleplayer", "unitcaps", "singleplayer.lua"), os.path.join("extras", "props", "fleetlimits.lua")):
        os.makedirs(os.path.dirname(os.path.join(RACES, "somtaaw", rel)), exist_ok=True)
        shutil.copyfile(os.path.join(KUS, rel), os.path.join(RACES, "somtaaw", rel))
    for fn in os.listdir(os.path.join(KUS, "scripts")):
        if fn.startswith(("ai_", "crate_")):
            os.makedirs(os.path.join(RACES, "somtaaw", "scripts"), exist_ok=True)
            shutil.copyfile(os.path.join(KUS, "scripts", fn), os.path.join(RACES, "somtaaw", "scripts", fn))

    b = ["-- Generated by tools/make_race.py: Somtaaw ships converted so far, gated by Cataclysm's research.",
         "Ship = 0", "SubSystem = 1", "build =", "{"]
    for ship, cat, prio in BUILD:
        req = " & ".join(ship_dep.get(cat.lower(), []))
        b += ["\t{", "\t\tType =\t\t\t\t\tShip,", f'\t\tThingToBuild =\t\t\t"{ship}",',
              f'\t\tRequiredResearch =\t\t"{req}",', '\t\tRequiredShipSubSystems =\t"",',
              f"\t\tDisplayPriority =\t\t{prio},", f'\t\tDisplayedName =\t\t\t"{ship[4:]}",',
              f'\t\tDescription =\t\t\t"{ship[4:]}",', "\t},"]
    b += ["}", ""]
    for fn in ("sp_build.lua", "def_build.lua"):
        write(os.path.join(RACES, "somtaaw", "scripts", fn), "\n".join(b))

    # Entries shaped like Gearbox's HW1 research (sp_research.lua): the Research subsystem (the Kuun-Lan's innate
    # HW1_ResearchModule) and a TargetName ship - the first converted ship the tech unlocks, else the Kuun-Lan.
    converted = {cat.lower(): ship for ship, cat, _ in BUILD}
    r = ["-- Generated by tools/make_race.py from researchdepend.script (SPRS* = single player).",
         'Icon_Tech = "data:ui/newui/research/icons/tech.mres"',
         'Icon_Build = "data:ui/newui/research/icons/build.mres"', "Modifier = 0", "Ability = 1", "AllShips = 0",
         "Family = 1", "Ship = 2", "research =", "{"]
    for i, (t, secs) in enumerate(sorted(techs.items())):
        req = " & ".join(tech_dep.get(t.lower(), []))
        unlocks = [converted[c] for c, deps in ship_dep.items() if t in deps and c in converted]
        r += ["\t{", f'\t\tName =\t\t\t\t"{t}",', f'\t\tRequiredResearch =\t"{req}",',
              '\t\tRequiredSubSystems =\t"Research",',
              f"\t\tCost =\t\t\t\t{secs * COST_PER_SECOND},", f"\t\tTime =\t\t\t\t{secs},",
              f'\t\tDisplayedName =\t\t"{tech_title(t)}",', f'\t\tShortDisplayedName =\t"{tech_title(t)}",',
              f"\t\tDisplayPriority =\t{10 + i},", f'\t\tDescription =\t\t"{tech_title(t)}",',
              f"\t\tIcon =\t\t\t\t{'Icon_Build' if unlocks else 'Icon_Tech'},",
              f'\t\tTargetName =\t\t"{unlocks[0] if unlocks else "Som_Mothership"}",', "\t},"]
    r += ["}", ""]
    for fn in ("sp_research.lua", "def_research.lua"):
        write(os.path.join(RACES, "somtaaw", "scripts", fn), "\n".join(r))

    write(os.path.join(MOD, "data", "scripts", "scar", "cataclysmtech.lua"),
          "-- Generated by tools/make_race.py: Cataclysm single-player techs (research option names).\n"
          "KAS_Techs = {" + ", ".join(f'"{t}"' for t in sorted(techs)) + "}\n")
    print(f"Somtaaw race: {len(BUILD)} ships, {len(techs)} techs "
          f"({sum(1 for t in techs if tech_dep.get(t.lower()))} with prerequisites)")


if __name__ == "__main__":
    main()
