"""Build Cataclysm's animatics (the movies between missions) for HWRM from the GOG install's Movies/AnimaticNN.bik and
Cataclysm-decomp/extracted/big/movies/animaticNN.script:
  data/animatics/animaticNN.webm   VP8 + Vorbis. The .bik is silent 640x480 video; Cataclysm plays the music and narration
                                   from the script at runtime (startMusic n, animaticSpeechEvent e at t seconds, with
                                   musicVolume / speechVolume). HWRM's own animatics carry their sound in the webm, so the
                                   script's mix is baked in here at its volumes.
  data/animatics/animaticNN.lua    MovieScreen (layout from HWRM's HW1 a00_01.lua; 4:3 kept, pillarboxed)
  data/locale/english/animatics/animaticNN_speech.lua   a subtitle per narration line (HW1's Actor_LocationCard pattern)
Inputs: music from Cataclysm-decomp/extracted/audio/music/music_NN.wav (ungained; tools/build_music.py's output is
gained for in-game play), speech from data/sound/speech/missions/cataclysm/<id>.wav (tools/build_speech.py; event ->
phrase as tools/nis2hwrm.py's speech_lookup). animatics.lst: AnimaticNN plays before mission NN (01 before Mission01).
The campaign file plays them: Mission[n].postload = playAnimatic("data:animatics/animaticNN.lua", 0, 0).

Usage: make_animatics.py [--subs-only] [NN ...]   (default: all 18; --subs-only skips the webm)
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nis2hwrm import speech_lookup  # noqa: E402

DECOMP = r"C:\Modding\Cataclysm-decomp"
GAME = r"C:\Games\Homeworld Emergence"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FFMPEG = r"C:\Modding\ffmpeg\bin\ffmpeg.exe"
SPEECH_DAT = "locale:leveldata/campaign/cataclysm/speech.dat"

MOVIE_LUA = """-- Generated by tools/make_animatics.py: Cataclysm Animatic{nn} (layout from HWRM's HW1 a00_01.lua, kept 4:3).
MovieScreen =
{{
	displayName = "Cataclysm Animatic {nn}",
	helpTip = "Cataclysm Animatic {nn}",

	Layout = {{size_WH = {{	w = 1, h = 1, wr = "scr", hr = "scr" }},}},

	stylesheet = "HW2StyleSheet",

	RootElementSettings =
	{{
		backgroundColor = {{0,0,0,255}},
	}},

	speechFilename = "locale:animatics/animatic{nn}_speech.lua",

	;
	{{
		type = "Movie",
		name = "MyMovie",

		Layout = {{
			pos_XY = {{ x = 0.5, y = 0.5, xr = "par", yr = "par" }},
			pivot_XY = {{ 0.5, 0.5 }},
			lockAspect = {w}/{h},
			size_WH = {{	w = 100000, h = 1, wr = "px", hr = "par" }},
			max_WH = {{	w = 1, h = 1, wr = "par", hr = "par" }},
		}},

		filenameV = "data:animatics/animatic{nn}.webm",
	}},
}}
"""


def parse_script(path):
    """-> (music [(t, track, volume)], speech [(t, event, volume)]). Times are seconds ("at frame 0" = 0)."""
    text = open(path, encoding="latin-1").read()
    text = text[text.rfind('#line 1 "Animatic'):]              # after the preprocessor's speechevent.h / soundmusic.h
    music, speech, t, vol = [], [], 0.0, {"music": 1.0, "speech": 1.0}
    for line in text.splitlines()[1:]:
        l = line.strip()
        if not l:
            continue
        m = re.match(r"at\s+(?:frame\s+(\d+)|([\d.]+))$", l)
        if m:
            t = int(m.group(1)) / 30 if m.group(1) else float(m.group(2))
            continue
        m = re.match(r"(musicVolume|speechVolume|SFXVolume)\s+([\d.]+)$", l)
        if m:
            vol[m.group(1)[:-6].lower()] = float(m.group(2))
            continue
        m = re.match(r"startMusic\s+(\d+)$", l)
        if m:
            music.append((t, int(m.group(1)), vol["music"]))
            continue
        m = re.match(r"animaticSpeechEvent\s+\((\d+)\s*\+", l)    # event + actor flag + 0x40000000
        if m:
            speech.append((t, int(m.group(1)), vol["speech"]))
            continue
        raise ValueError(f"{path}: unhandled line {l!r}")
    return music, speech


def sss_ff(t):
    """Seconds -> HWRM's speech-file time (sss.ff: whole seconds + frames of 30 fps)."""
    s = int(t)
    return f"{s}.{round((t - s) * 30):02d}"


def build(nn, events, video=True):
    script = os.path.join(DECOMP, "extracted", "big", "movies", f"animatic{nn}.script")
    bik = os.path.join(GAME, "Movies", f"Animatic{nn}.bik")
    music, speech = parse_script(script)
    out_dir = os.path.join(MOD, "data", "animatics")
    loc_dir = os.path.join(MOD, "data", "locale", "english", "animatics")
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(loc_dir, exist_ok=True)

    inputs, chains = ["-i", bik], []
    for t, track, vol in music:
        inputs += ["-i", os.path.join(DECOMP, "extracted", "audio", "music", f"music_{track:02d}.wav")]
        chains.append((t, vol))
    subs = []
    for t, ev, vol in speech:
        sid, secs, text, _ = events[ev]
        inputs += ["-i", os.path.join(MOD, "data", "sound", "speech", "missions", "cataclysm", f"{sid}.wav")]
        chains.append((t, vol))
        subs.append((t, sid, secs, text))
    filt = [f"[{i + 1}:a]aresample=44100,aformat=channel_layouts=stereo,volume={vol},adelay={round(t * 1000)}:all=1[a{i}]"
            for i, (t, vol) in enumerate(chains)]
    filt.append("".join(f"[a{i}]" for i in range(len(chains)))
                + f"amix=inputs={len(chains)}:normalize=0:duration=longest:dropout_transition=0[mix]")
    # -shortest cuts the mix at the video's end (the music outlasts it)
    webm = os.path.join(out_dir, f"animatic{nn}.webm")
    if video:
        subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-y", *inputs,
                        "-filter_complex", ";".join(filt), "-map", "0:v", "-map", "[mix]",
                        "-c:v", "libvpx", "-crf", "4", "-b:v", "4M", "-c:a", "libvorbis", "-q:a", "6", "-shortest",
                        webm], check=True)

    with open(os.path.join(out_dir, f"animatic{nn}.lua"), "w", newline="\n") as f:
        f.write(MOVIE_LUA.format(nn=nn, w=640, h=480))
    with open(os.path.join(loc_dir, f"animatic{nn}_speech.lua"), "w", newline="\n") as f:
        f.write(f"-- Generated by tools/make_animatics.py from Cataclysm's animatic{nn}.script. The narration is in the\n"
                f"-- webm; these show its subtitles (speech.dat) as HWRM's HW1 animatics do. A subtitle event also plays\n"
                f"-- <speech folder>/<id>.wav, so the folder must not hold the narration (with it, it played twice).\n\n"
                f'SetSpeechFolder( "Data:Sound/Speech/animatic/cataclysm" );\n'
                f'AddLocalizedText( "{SPEECH_DAT}" );\n\n')
        for t, sid, secs, text in subs:
            f.write(f"-- {secs:.1f}s: {text[:90]}\n"
                    f'AddSubtitleEvent( {sss_ff(t)}, Actor_LocationCard, "${sid}", {secs:.1f} );\n')
            # 4th argument: a float the handler (HWRM FUN_0054f4ef) stores per subtitle; HW1's 0 shows a card briefly
    print(f"animatic{nn}: {len(music)} music, {len(speech)} speech -> {webm}")


def main():
    video = "--subs-only" not in sys.argv
    wanted = [a for a in sys.argv[1:] if a != "--subs-only"] or [f"{n:02d}" for n in range(1, 19)]
    events = speech_lookup()
    for nn in wanted:
        build(f"{int(nn):02d}", events, video)


if __name__ == "__main__":
    main()
