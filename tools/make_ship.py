"""Write data/ship/<name>/<name>.ship for a converted Cataclysm ship, from a stock HWRM ship used as template.

Stats come from Cataclysm's .shp, scaled the way Gearbox scaled HW1 -> HWRM for the template ship (ratio of the
template's HWRM value to its HW1 value): maxhealth, speeds. Build cost and time stay Cataclysm's (its economy).
The template's weapons are re-bound to the model's gun joints (geo2dae.py: Weapon_GUN<n>), its hardpoints, custom
code and research-gated extras are dropped, and BuildFamily becomes "<Class>_Som" for the Somtaaw build list.

Usage: make_ship.py [name ...]   (default: every ship in SHIPS)
"""
import os
import re
import sys

DECOMP = r"C:\Modding\Cataclysm-decomp"
MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HW1 = os.path.join(DECOMP, "reference", "hw1classic", "r1")
HWRM_SHIPS = os.path.join(DECOMP, "reference", "hwrm", "HW1Ships", "ship")

# name: (Cataclysm .shp, displayed name, description, HWRM template, HW1 .shp of the template, build family,
#        guns bound to the template's first weapon)
SHIPS = {
    "som_worker": ("sworker", "Worker", "Resource collector and repair vessel", "kus_resourcecollector",
                   "resourcecollector", "Resource_Som", []),
    "som_recon": ("srecon", "Recon", "Fast reconnaissance craft", "kus_scout", "lightinterceptor",
                  "Fighter_Som", ["GUN0"]),
    "som_acolyte": ("sacolyte", "Acolyte", "Fighter", "kus_interceptor", "heavyinterceptor", "Fighter_Som",
                    ["GUN0", "GUN1"]),
}


def shp_values(path):
    v = {}
    for line in open(path, encoding="latin-1"):
        m = re.match(r"\s*([A-Za-z_]+)\s+([-\d.]+)", line.split(";")[0])
        if m and m.group(1) not in v:
            v[m.group(1)] = float(m.group(2))
    return v


def ship_value(text, key):
    m = re.search(key + r'\s*=\s*(?:getShipNum\(NewShipType,\s*"\w+",\s*)?([\d.]+)(?:\*([\d.]+))?', text)
    if not m:
        return None
    return float(m.group(1)) * (float(m.group(2)) if m.group(2) else 1.0)


def make(name):
    cat, disp, desc, tmpl, hw1, family, guns = SHIPS[name]
    c = shp_values(os.path.join(DECOMP, "extracted", "big", "race_sect", cat + ".shp"))
    h = shp_values(os.path.join(HW1, hw1 + ".shp"))
    t = open(os.path.join(HWRM_SHIPS, tmpl, tmpl + ".ship"), encoding="latin-1").read()
    r_health = ship_value(t, r"NewShipType\.maxhealth") / h["maxhealth"]
    r_speed = ship_value(t, r"NewShipType\.mainEngineMaxSpeed") / h["maxvelocity"]
    health = round(c["maxhealth"] * r_health)
    speed = round(c["maxvelocity"] * r_speed)
    weapon = re.search(r'StartShipWeaponConfig\(NewShipType,\s*"([^"]+)"', t)
    out = []
    for line in t.splitlines():
        if line.startswith(("StartShipWeaponConfig", "StartShipHardPointConfig", "addCustomCode")):
            continue
        line = re.sub(r'displayedName="[^"]*"', f'displayedName="{disp}"', line)
        line = re.sub(r'sobDescription="[^"]*"', f'sobDescription="{desc}"', line)
        line = re.sub(r'("maxhealth",\s*)[\d.]+', rf"\g<1>{health}", line)
        line = re.sub(r"^(NewShipType\.(?:thrusterMaxSpeed|mainEngineMaxSpeed))=.*", rf"\1={speed}", line)
        line = re.sub(r"^NewShipType\.buildCost=.*", f"NewShipType.buildCost={int(c['buildCost'])}", line)
        line = re.sub(r"^NewShipType\.buildTime=.*", f"NewShipType.buildTime={int(c['buildTime'])}", line)
        line = re.sub(r'^NewShipType\.BuildFamily=.*', f'NewShipType.BuildFamily="{family}"', line)
        out.append(line)
    if weapon:
        out += [f'StartShipWeaponConfig(NewShipType,"{weapon.group(1)}","Weapon_{g}","");' for g in guns]
    head = (f"-- {name}: Cataclysm {cat} (generated by tools/make_ship.py; template {tmpl}).\n"
            f"-- maxhealth {c['maxhealth']:g} x {r_health:.3f}, maxvelocity {c['maxvelocity']:g} x {r_speed:.3f} "
            f"(the template's HWRM/HW1 ratios); build cost/time from Cataclysm.\n")
    d = os.path.join(MOD, "data", "ship", name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, name + ".ship"), "w", encoding="latin-1", newline="\n") as f:
        f.write(head + "\n".join(out) + "\n")
    print(f"{name}: health {health}, speed {speed}, cost {int(c['buildCost'])}, time {int(c['buildTime'])}, "
          f"weapons {weapon.group(1) if weapon else '-'} x{len(guns)}")


def main():
    for n in sys.argv[1:] or SHIPS:
        make(n)


if __name__ == "__main__":
    main()
